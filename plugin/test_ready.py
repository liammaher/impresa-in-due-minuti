#!/usr/bin/env python3
"""docs/ready.md, offline: how ready.py draws the page from the catalog and scoreboard's counts, that
`scoreboard.py --write` writes it with coverage.md on one date, and that the committed pages agree
(the counts, the date, the plugin's version), so a coverage.md regenerated without it fails here.

  python3 plugin/test_ready.py      (needs PyYAML, as build.py does)
"""

import json
import re
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path[:0] = [str(HERE), str(REPO / "claude" / "skills" / "pratica" / "portal")]
sys.dont_write_bytecode = True
import ready  # noqa: E402
import scoreboard  # noqa: E402

STEPS = {
    "a-fittizia": {"generated": "gen.py from sue-a (2026-11-01) and dictionary/fnsuap.yaml",
                   "wizard": [{"screen": "Scelta operazioni", "tree": "Alpha | Op"}],
                   "supports": [{"when": "x", "else": "No beta | here."}, {"when": "y", "else": "Only alpha."}, {"if": "z"}]},
    "b-fittizia": {"generated": "gen.py from sue-b (2026-11-01) and dictionary/fnsuap.yaml",
                   "wizard": [{"screen": "Scelta operazioni", "tree": ["One", "Two"]}],
                   "supports": [{"when": "x", "else": "Only alpha."}]},
    "c-fittizia": {"generated": "written by hand", "title": "Gamma", "supports": []},
}
CATALOG = [{"name": n, "procedure": f"napoli/comune/{n[0]}", "sportello": "sue"} for n in ("b-fittizia", "a-fittizia", "c-fittizia")]
STATUS = {"sue-a": {"missing": []}, "sue-b": {"missing": ["Some section"]}}
REH = {"a-fittizia": {"run": True}, "b-fittizia": {"run": False}}


def page(rows, **over):
    args = dict(version="9.9.9", commit="abc123", dirty=False, today="2026-01-02", desks={"sue"},
                counts=[("sue", 2, 1, 1)], names=scoreboard.NAMES, claims=scoreboard.CLAIMS, no_real_case="No real case yet.")
    return ready.render(rows, **(args | over))


def section(text, title):
    return re.search(rf"^## {title}\n(.*?)(?=^## |\Z)", text, re.S | re.M).group(1)


def table(block):
    return [[c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]] for line in block.splitlines() if line.startswith("| `")]


def main():
    # One row per steps file, sorted; a status is the scoreboard's, a refusal is a deduplicated `else`.
    rows = ready.rows_from(CATALOG, STEPS.get, STATUS, REH)
    assert [r["name"] for r in rows] == ["a-fittizia", "b-fittizia", "c-fittizia"], rows
    a, b, c = rows
    assert (a["mapped"], a["fillable"], a["run"]) == (True, True, True), a
    assert (b["mapped"], b["fillable"], b["run"]) == (True, False, False), b  # a section short: mapped, not fillable
    assert (c["mapped"], c["fillable"], c["run"]) == (False, False, False), c  # no crawl named: nothing is claimed
    assert a["portal"] == "Alpha | Op" and b["portal"] == "One + Two" and c["portal"] == "Gamma", rows
    assert a["refusals"] == ["No beta | here.", "Only alpha."] and c["refusals"] == [], a

    text = page(rows)
    assert "<!-- Generated by plugin/ready.py on 2026-01-02; do not edit by hand. -->" in text, text
    assert "| Plugin version | 9.9.9 " in text and "| Repo commit | `abc123` |" in text and "| Generated | 2026-01-02 |" in text
    assert "| Sportelli shipped | SUE (building works), as " in text
    assert "| Not shipped | SUAP (businesses): mapped in the repo, not in the plugin |" in text, "a sportello apart is said so"
    assert "plus uncommitted changes" not in text and "plus uncommitted changes" in page(rows, dirty=True)
    assert scoreboard.CLAIMS.rstrip("\n") in text, "the claims are coverage.md's words"
    assert "| SUE (building works) | 2 | 1 | 1 |" in text and "SUAP (businesses) |" not in section(text, "Counts")
    assert "carries 3 steps files for 3 pratiche" in text, text  # c has no crawl: counted as its own
    assert "1 of the 3 have a run" in text, text
    pratiche = table(section(text, "Pratiche"))
    assert [r[0] for r in pratiche] == ["`napoli/comune/a`", "`napoli/comune/b`", "`napoli/comune/c`"], pratiche
    assert pratiche[0][3:6] == ["yes", "yes", "yes"] and pratiche[1][3:6] == ["yes", "no", "no"], pratiche
    assert pratiche[0][1] == "Alpha \\| Op", "a | in a cell is escaped"
    assert pratiche[2][6] == "none"
    # Each refusal once, by a stable id, with the number of rows that carry it; every id a row names is defined.
    refused = table(section(text, "Refusals"))
    assert [r[2] for r in refused] == ["Only alpha.", "No beta \\| here."], refused  # most shared first
    assert [r[1] for r in refused] == ["2", "1"], refused
    defined = {r[0].strip("`") for r in refused}
    assert {i for r in pratiche for i in re.findall(r"`(r[0-9a-f]{6})`", r[6])} == defined
    assert ready.refusal_id("Only alpha.") == ready.refusal_id("Only alpha.") != ready.refusal_id("Only beta.")
    assert page(rows, desks={"sue", "suap"}).count("Not shipped | none") == 1

    # scoreboard.py --write writes both pages on one date, coverage.md first.
    calls = []
    with tempfile.TemporaryDirectory() as tmp:
        real = (scoreboard.OUT, scoreboard.render, ready.OUT, ready.generate)
        try:
            scoreboard.OUT, ready.OUT = Path(tmp) / "coverage.md", Path(tmp) / "ready.md"
            scoreboard.render = lambda today=None: calls.append(("coverage", today)) or "COVERAGE\n"
            ready.generate = lambda today=None: calls.append(("ready", today)) or "READY\n"
            scoreboard.write("2026-03-04")
            assert calls == [("coverage", "2026-03-04"), ("ready", "2026-03-04")], calls
            assert scoreboard.OUT.read_text() == scoreboard.HEAD + "COVERAGE\n" and ready.OUT.read_text() == "READY\n"
        finally:
            scoreboard.OUT, scoreboard.render, ready.OUT, ready.generate = real

    # The committed pages agree: same date, same counts for each shipped sportello, this plugin version.
    coverage, committed = (REPO / "docs" / "coverage.md").read_text(), (REPO / "docs" / "ready.md").read_text()
    date_c = re.search(r"scoreboard\.py on (\d{4}-\d\d-\d\d);", coverage).group(1)
    date_r = re.search(r"plugin/ready\.py on (\d{4}-\d\d-\d\d);", committed).group(1)
    assert date_c == date_r, f"coverage.md is of {date_c}, ready.md of {date_r}: run `make coverage`"
    version = json.loads((HERE / "impresa-in-un-minuto" / ".claude-plugin" / "plugin.json").read_text())["version"]
    assert f"| Plugin version | {version} " in committed, f"ready.md is not of plugin {version}: run `make coverage`"
    desks = set(yaml.safe_load((HERE / "build.yaml").read_text())["sportelli"])
    for sp, name in scoreboard.NAMES.items():
        row = re.search(rf"^\| {re.escape(name)} \| (\d+) \| (\d+) \| (\d+) \|", coverage, re.M).groups()
        got = re.search(rf"^\| {re.escape(name)} \| (\d+) \| (\d+) \| (\d+) \|$", section(committed, "Counts"), re.M)
        assert (got and got.groups()) == (row if sp in desks else None), f"{name}: coverage.md {row}, ready.md {got and got.groups()}"
    rows = table(section(committed, "Pratiche"))
    # One row per steps file: several share a library procedure (the SUAP's SCIA opens, moves, enlarges).
    files = [r[2] for r in rows]
    assert rows and len(files) == len(set(files)), "one row per steps file"
    assert f"carries {len(rows)} steps files for " in committed
    for r in rows:
        assert (REPO / "rehearsals" / r[2].strip("`")).is_dir(), r
        assert r[3:6] and all(x in ("yes", "no") for x in r[3:6]), r
    named = {i for r in rows for i in re.findall(r"`(r[0-9a-f]{6})`", r[6])}
    assert named == {r[0].strip("`") for r in table(section(committed, "Refusals"))}, "every refusal is named by a row"
    print("ok: ready.md is drawn from the catalog and the scoreboard, written with coverage.md, and agrees with it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
