#!/usr/bin/env python3
"""docs/ready.md: the one machine-written list of what the released plugin can do.

  ready.py            print it
  ready.py --write    rewrite docs/ready.md

`scoreboard.py --write` (or `make coverage`) writes it too, from the same counts and the same date as
docs/coverage.md, so the two never drift. Nothing here is typed by hand:

  - the shipped pratiche are build.py's catalog (copy_pratiche, the list the plugin's catalog.json
    holds): a rehearsal's steps file for each of build.yaml's `sportelli`, built from its recipe and
    held to rehearsals/steps.lock as the build holds it;
  - mapped, fillable and run on the portal are scoreboard.py's, word for word the claims at the top of
    docs/coverage.md; the counts are scoreboard.build()'s own;
  - the refusals are the cases a steps file turns away (its `supports`), which the plugin's pre-flight
    reports and the connector reads there.

Run it with the pratica venv's Python (build.py and gen.py need PyYAML), like the scoreboard.
"""

import argparse
import datetime as dt
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
PORTAL = REPO / "claude" / "skills" / "pratica" / "portal"
OUT = REPO / "docs" / "ready.md"
MANIFEST = HERE / "impresa-in-un-minuto" / ".claude-plugin" / "plugin.json"
SCRIPT = "plugin/ready.py"


def crawl_of(steps):
    """The portal crawl a steps file was generated from (its `generated` line says)."""
    m = re.match(r"gen\.py from (\S+) ", steps.get("generated", ""))
    return m.group(1) if m else None


def portal_name(steps):
    """The operation(s) the run picks on the portal ('Scelta operazioni'); a combination's are joined."""
    for screen in steps.get("wizard", []):
        if screen.get("screen") == "Scelta operazioni" and screen.get("tree"):
            tree = screen["tree"]
            return " + ".join(tree if isinstance(tree, list) else [tree])
    return steps.get("title") or ""


def refusals_of(steps):
    """The cases a steps file turns away, as it words them for the person (deduplicated, in order)."""
    seen = []
    for s in steps.get("supports", []):
        if "else" in s and s["else"] not in seen:
            seen.append(s["else"])
    return seen


def refusal_id(message):
    """A refusal's name: a hash of its text, so it stays the same while the text does."""
    return "r" + hashlib.sha1(message.encode()).hexdigest()[:6]


def rows_from(catalog, steps_of, status, reh):
    """One row per catalog entry (a steps file the plugin carries).

    mapped / fillable: the entry's crawl is in scoreboard's status, with no section short.
    run: this entry's own rehearsal has a run that filled the draft (reh, as scoreboard counts it)."""
    rows = []
    for e in catalog:
        steps = steps_of(e["name"])
        crawl = crawl_of(steps)
        st = status.get(crawl)
        rows.append({
            "slug": e["procedure"], "name": e["name"], "sportello": e["sportello"], "crawl": crawl,
            "portal": portal_name(steps),
            "mapped": st is not None, "fillable": st is not None and not st["missing"],
            "run": bool(reh.get(e["name"], {}).get("run")),
            "refusals": refusals_of(steps),
        })
    return sorted(rows, key=lambda r: (r["sportello"], r["slug"], r["name"]))


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def yes(flag):
    return "yes" if flag else "no"


def render(rows, *, version, commit, dirty, today, desks, counts, names, claims, no_real_case):
    """The page. counts: scoreboard's (sportello, mapped, fillable, run) per carried sportello;
    names: scoreboard.NAMES; claims: its CLAIMS text."""
    shipped = [names[d] for d in names if d in desks]
    apart = [names[d] for d in names if d not in desks]
    refusals = {}
    for r in rows:
        for m in r["refusals"]:
            refusals.setdefault(refusal_id(m), m)
    steps_n, crawls_n = len(rows), len({r["crawl"] or r["name"] for r in rows})  # hand-written steps: its own
    out = [
        "# Ready: what the released plugin can do", "",
        f"<!-- Generated by {SCRIPT} on {today}; do not edit by hand. -->", "",
        "The single list of what the plugin ships, written by `claude/skills/pratica/portal/scoreboard.py --write` "
        "(`make coverage`) from the same counts as [coverage.md](coverage.md). Read this, not a hand-built list.", "",
        "| | |", "|---|---|",
        f"| Plugin version | {version} (`plugin/impresa-in-un-minuto/.claude-plugin/plugin.json`) |",
        f"| Repo commit | `{commit}`{' plus uncommitted changes' if dirty else ''} |",
        f"| Generated | {today} |",
        f"| Sportelli shipped | {', '.join(shipped)}, as `plugin/build.yaml` `sportelli` says |",
        f"| Not shipped | {', '.join(apart) + ': mapped in the repo, not in the plugin' if apart else 'none'} |", "",
        "The three claims, as [coverage.md](coverage.md) states them:", "", claims.rstrip("\n"), "",
        f"{no_real_case} Every row below stops short of it.", "",
        "## Counts", "",
        "Per pratica on the portal, as coverage.md counts them:", "",
        "| Sportello | Mapped | Fillable | Run on the portal |", "|---|---:|---:|---:|",
    ]
    out += [f"| {names[sp]} | {m} | {f} | {r} |" for sp, m, f, r in counts]
    out += ["",
            f"The plugin carries {steps_n} steps files for {crawls_n} pratiche on the portal (a few steps files share one "
            f"pratica, filled with other choices); {sum(r['run'] for r in rows)} of the {steps_n} have a run that filled "
            "the draft. The rows below are per steps file.", "",
            "## Pratiche", "",
            "| Library slug | Portal name | Steps file | Mapped | Fillable | Run on the portal | Refusals |",
            "|---|---|---|---|---|---|---|"]
    for r in rows:
        ids = " ".join(f"`{refusal_id(m)}`" for m in r["refusals"]) or "none"
        out.append(f"| `{r['slug']}` | {cell(r['portal'])} | `{r['name']}` | {yes(r['mapped'])} | {yes(r['fillable'])} "
                   f"| {yes(r['run'])} | {ids} |")
    out += ["", "## Refusals", "",
            "What a steps file turns away, in the words the person reads (Italian), by the id each row names. "
            "Cases the rules tables refuse by law are in the library, not listed here.", "",
            "| Id | Rows | Refusal |", "|---|---:|---|"]
    for rid, msg in sorted(refusals.items(), key=lambda kv: (-sum(rid_in(r, kv[0]) for r in rows), kv[0])):
        out.append(f"| `{rid}` | {sum(rid_in(r, rid) for r in rows)} | {cell(msg)} |")
    return "\n".join(out) + "\n"


def rid_in(row, rid):
    return any(refusal_id(m) == rid for m in row["refusals"])


def git(*args):
    r = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def generate(today=None):
    sys.path[:0] = [str(PORTAL), str(HERE)]
    sys.dont_write_bytecode = True
    import build  # plugin/build.py: the catalog the plugin ships
    import scoreboard  # the counts coverage.md prints (cached: one pass for both pages)

    today = today or dt.date.today().isoformat()
    lines, _, reh, status = scoreboard.build()
    desks = build.sportelli()
    with tempfile.TemporaryDirectory() as tmp:
        skill = Path(tmp)
        # No library: its path only adds catalog.json's `library` link, which this page doesn't show.
        catalog = build.copy_pratiche(skill, skill / "no-library", desks)
        rows = rows_from(catalog, lambda n: json.loads((skill / "pratiche" / f"{n}.json").read_text()), status, reh)
    counts = [(sp, m, f, r) for sp, m, f, r, *_ in lines if sp in desks]
    # The checkout's changes other than the two generated pages, which this very run rewrites.
    dirty = bool(git("status", "--porcelain", "--untracked-files=no", "--", ".", ":!docs/coverage.md", ":!docs/ready.md"))
    return render(rows, version=json.loads(MANIFEST.read_text())["version"], commit=git("rev-parse", "HEAD") or "unknown",
                  dirty=dirty, today=today, desks=desks, counts=counts, names=scoreboard.NAMES,
                  claims=scoreboard.CLAIMS, no_real_case=scoreboard.NO_REAL_CASE)


def write(today=None):
    OUT.write_text(generate(today))
    print("wrote", OUT)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help="rewrite docs/ready.md (default: print it)")
    a = ap.parse_args()
    if a.write:
        write()
    else:
        print(generate())
